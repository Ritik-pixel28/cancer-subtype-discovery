    def execute(self) -> CharacterizationResult:
        """Run complete Phase 8 analysis workflow."""
        LOGGER.info("Starting Phase 8 Subtype Characterization...")
        self.output_dir.mkdir(parents=True, exist_ok=True)

        # 1. Validate inputs
        self.validate_inputs()

        # 2. Build summaries and tables
        LOGGER.info("Generating cluster summaries...")
        summary_df = self.build_cluster_summaries()

        LOGGER.info("Integrating biomarker findings...")
        biomarker_df = self.build_biomarker_integration()

        LOGGER.info("Integrating pathway enrichments...")
        pathway_df = self.build_pathway_integration()

        LOGGER.info("Performing cross-cluster statistical comparisons...")
        cross_df = self.build_cross_cluster_comparison()

        # 3. Generate figures
        LOGGER.info("Generating scientific visualizations...")
        fig_paths = self.generate_figures()

        # 4. Generate report markdown
        LOGGER.info("Synthesizing markdown characterization report...")
        report_md = self.generate_report_markdown(summary_df, biomarker_df, pathway_df, cross_df)

        # 5. Persist artifacts
        summary_path = self.output_dir / "subtype_characterization_summary.csv"
        biomarker_path = self.output_dir / "cluster_biomarker_summary.csv"
        pathway_path = self.output_dir / "cluster_pathway_summary.csv"
        cross_path = self.output_dir / "cross_cluster_comparison.csv"
        report_path = self.output_dir / "subtype_characterization_report.md"
        meta_path = self.output_dir / "phase8_run_metadata.json"

        summary_df.to_csv(summary_path, index=False)
        biomarker_df.to_csv(biomarker_path, index=False)
        pathway_df.to_csv(pathway_path, index=False)
        cross_df.to_csv(cross_path, index=False)
        report_path.write_text(report_md, encoding="utf-8")

        # 6. Build metadata
        meta = {
            "phase": 8,
            "title": "Integrated Biological Interpretation and Subtype Characterization",
            "run_timestamp_utc": datetime.now(timezone.utc).isoformat(),
            "inputs": self.input_manifest,
            "outputs": {
                "subtype_characterization_summary": str(summary_path.resolve()),
                "cluster_biomarker_summary": str(biomarker_path.resolve()),
                "cluster_pathway_summary": str(pathway_path.resolve()),
                "cross_cluster_comparison": str(cross_path.resolve()),
                "subtype_characterization_report": str(report_path.resolve()),
                "figures": {k: str(p.resolve()) for k, p in fig_paths.items()},
            },
            "parameters": {
                "fdr_threshold": 0.05,
                "strong_rank_biserial_threshold": 0.8,
                "multiple_testing": "Benjamini-Hochberg (inherited from Phase 6 and 7)",
                "contingency_test": "Two-sided Fisher's Exact Test",
            },
            "software_versions": {
                "python": sys.version,
                "numpy": np.__version__,
                "pandas": pd.__version__,
                "matplotlib": matplotlib.__version__,
            },
            "status": "COMPLETED",
        }
        meta_path.write_text(json.dumps(meta, indent=2), encoding="utf-8")
        LOGGER.info("Phase 8 artifacts written to %s", self.output_dir)

        return CharacterizationResult(
            subtype_summary=summary_df,
            biomarker_summary=biomarker_df,
            pathway_summary=pathway_df,
            cross_cluster_comparison=cross_df,
            metadata=meta,
            report_markdown=report_md,
            figure_paths=fig_paths,
        )


