class SubtypeCharacterizer:
    """
    Synthesizes and characterizes cancer subtypes discovered in Phase 5
    using Phase 6 biomarker candidates and Phase 7 pathway enrichment.
    """

    def __init__(
        self,
        clusters_path: Path,
        labels_path: Path,
        pca_path: Path,
        biomarkers_path: Path,
        strong_candidates_path: Path,
        enrichment_all_path: Path,
        enrichment_sig_path: Path,
        enrichment_summary_path: Path,
        output_dir: Path,
    ):
        self.clusters_path = Path(clusters_path)
        self.labels_path = Path(labels_path)
        self.pca_path = Path(pca_path)
        self.biomarkers_path = Path(biomarkers_path)
        self.strong_candidates_path = Path(strong_candidates_path)
        self.enrichment_all_path = Path(enrichment_all_path)
        self.enrichment_sig_path = Path(enrichment_sig_path)
        self.enrichment_summary_path = Path(enrichment_summary_path)
        self.output_dir = Path(output_dir)
        self.figures_dir = self.output_dir / "figures"

        self.clusters_df: pd.DataFrame = pd.DataFrame()
        self.labels_df: pd.DataFrame = pd.DataFrame()
        self.pca_df: pd.DataFrame = pd.DataFrame()
        self.all_biomarkers_df: pd.DataFrame = pd.DataFrame()
        self.strong_candidates_df: pd.DataFrame = pd.DataFrame()
        self.enrichment_all_df: pd.DataFrame = pd.DataFrame()
        self.enrichment_sig_df: pd.DataFrame = pd.DataFrame()
        self.enrichment_summary_df: pd.DataFrame = pd.DataFrame()

        self.input_manifest: Dict[str, Dict[str, Any]] = {}

    def validate_inputs(self) -> None:
        """Verify presence, integrity, and compatibility of all required input files."""
        required_files = [
            ("clusters", self.clusters_path),
            ("labels", self.labels_path),
            ("pca", self.pca_path),
            ("biomarkers", self.biomarkers_path),
            ("strong_candidates", self.strong_candidates_path),
            ("enrichment_all", self.enrichment_all_path),
            ("enrichment_sig", self.enrichment_sig_path),
            ("enrichment_summary", self.enrichment_summary_path),
        ]

        for name, path in required_files:
            if not path.is_file():
                raise FileNotFoundError(f"Required Phase input missing: {path}")
            self.input_manifest[name] = {
                "path": str(path.resolve()),
                "sha256": calculate_sha256(path),
                "size_bytes": path.stat().st_size,
            }

        # Load and validate clusters
        self.clusters_df = pd.read_csv(self.clusters_path)
        if "sample_id" not in self.clusters_df.columns or "cluster" not in self.clusters_df.columns:
            raise ValueError(f"Clusters table missing required columns in {self.clusters_path}")
        if self.clusters_df["sample_id"].isna().any() or self.clusters_df["sample_id"].duplicated().any():
            raise ValueError("Clusters table contains missing or duplicate sample IDs.")
        self.clusters_df["sample_id"] = self.clusters_df["sample_id"].astype(str)
        self.clusters_df["cluster"] = pd.to_numeric(self.clusters_df["cluster"], errors="raise").astype(int)

        # Load and validate labels
        self.labels_df = pd.read_csv(self.labels_path)
        if "sample_id" not in self.labels_df.columns or "cancer_type" not in self.labels_df.columns:
            raise ValueError(f"Labels table missing required columns in {self.labels_path}")
        self.labels_df["sample_id"] = self.labels_df["sample_id"].astype(str)

        # Check sample alignment
        cluster_samples = set(self.clusters_df["sample_id"])
        label_samples = set(self.labels_df["sample_id"])
        if cluster_samples != label_samples:
            raise ValueError(
                f"Sample ID mismatch between clusters ({len(cluster_samples)}) and labels ({len(label_samples)})."
            )

        # Load and validate PCA
        self.pca_df = pd.read_csv(self.pca_path)
        required_pca_cols = {"sample_id", "PC1", "PC2", "PC3", "cluster"}
        if not required_pca_cols.issubset(self.pca_df.columns):
            raise ValueError(f"PCA table missing columns in {self.pca_path}")
        self.pca_df["sample_id"] = self.pca_df["sample_id"].astype(str)
        self.pca_df["cluster"] = pd.to_numeric(self.pca_df["cluster"], errors="raise").astype(int)

        # Load and validate biomarkers
        self.all_biomarkers_df = pd.read_csv(self.biomarkers_path)
        required_bio_cols = {"gene", "cluster", "mann_whitney_u", "p_value", "rank_biserial", "fdr", "significant"}
        if not required_bio_cols.issubset(self.all_biomarkers_df.columns):
            raise ValueError(f"All biomarkers table missing columns in {self.biomarkers_path}")
        self.all_biomarkers_df["cluster"] = pd.to_numeric(self.all_biomarkers_df["cluster"], errors="raise").astype(int)

        # Load and validate strong candidates
        self.strong_candidates_df = pd.read_csv(self.strong_candidates_path)
        required_strong_cols = {"gene", "cluster", "rank_biserial", "fdr", "direction"}
        if not required_strong_cols.issubset(self.strong_candidates_df.columns):
            raise ValueError(f"Strong candidates table missing columns in {self.strong_candidates_path}")
        self.strong_candidates_df["cluster"] = pd.to_numeric(self.strong_candidates_df["cluster"], errors="raise").astype(int)

        # Load and validate pathway enrichments
        self.enrichment_all_df = pd.read_csv(self.enrichment_all_path)
        self.enrichment_sig_df = pd.read_csv(self.enrichment_sig_path)
        self.enrichment_summary_df = pd.read_csv(self.enrichment_summary_path)

        required_enrich_cols = {"Term", "P-value", "FDR_BH", "cluster", "gene_set_library", "overlap_count"}
        if not required_enrich_cols.issubset(self.enrichment_all_df.columns):
            raise ValueError(f"Enrichment all results missing columns in {self.enrichment_all_path}")
        self.enrichment_all_df["cluster"] = pd.to_numeric(self.enrichment_all_df["cluster"], errors="raise").astype(int)

        if not self.enrichment_sig_df.empty:
            self.enrichment_sig_df["cluster"] = pd.to_numeric(self.enrichment_sig_df["cluster"], errors="raise").astype(int)

        LOGGER.info(
            "Input validation passed successfully: %d samples, %d total biomarker rows, %d strong candidates, %d enrichment tests.",
            len(self.clusters_df),
            len(self.all_biomarkers_df),
            len(self.strong_candidates_df),
            len(self.enrichment_all_df),
        )

    def build_cluster_summaries(self) -> pd.DataFrame:
        """
        Build cluster-level characterization summaries:
        - Sample counts and proportions
        - Known ALL/AML composition
        - PCA location (centroid & spread)
        - Biomarker counts (tested, significant, strong, higher/lower)
        - Pathway enrichment counts (overall and per library)
        """
        merged_samples = self.clusters_df.merge(self.labels_df, on="sample_id")
        merged_pca = merged_samples.merge(self.pca_df[["sample_id", "PC1", "PC2", "PC3"]], on="sample_id")

        total_samples = len(merged_samples)
        clusters = sorted(self.clusters_df["cluster"].unique())

        rows = []
        for c in clusters:
            sub_samples = merged_samples[merged_samples["cluster"] == c]
            sub_pca = merged_pca[merged_pca["cluster"] == c]
            n_samples = len(sub_samples)
            prop = n_samples / total_samples

            all_count = int((sub_samples["cancer_type"] == "ALL").sum())
            aml_count = int((sub_samples["cancer_type"] == "AML").sum())
            all_pct = (all_count / n_samples) * 100.0 if n_samples > 0 else 0.0
            aml_pct = (aml_count / n_samples) * 100.0 if n_samples > 0 else 0.0

            # PCA statistics
            mean_pc1 = float(sub_pca["PC1"].mean())
            mean_pc2 = float(sub_pca["PC2"].mean())
            mean_pc3 = float(sub_pca["PC3"].mean())
            std_pc1 = float(sub_pca["PC1"].std(ddof=1)) if n_samples > 1 else 0.0
            std_pc2 = float(sub_pca["PC2"].std(ddof=1)) if n_samples > 1 else 0.0
            std_pc3 = float(sub_pca["PC3"].std(ddof=1)) if n_samples > 1 else 0.0

            # Biomarker counts
            sub_bio = self.all_biomarkers_df[self.all_biomarkers_df["cluster"] == c]
            tested_probes = len(sub_bio)
            fdr_sig = int((sub_bio["fdr"] <= 0.05).sum())

            sub_strong = self.strong_candidates_df[self.strong_candidates_df["cluster"] == c]
            strong_count = len(sub_strong)
            strong_higher = int((sub_strong["direction"] == "higher").sum())
            strong_lower = int((sub_strong["direction"] == "lower").sum())

            # Pathway counts from enrichment_sig_df
            if not self.enrichment_sig_df.empty:
                sub_paths = self.enrichment_sig_df[self.enrichment_sig_df["cluster"] == c]
                total_sig_paths = len(sub_paths)
                kegg_paths = int((sub_paths["gene_set_library"] == "KEGG_2021_Human").sum())
                reactome_paths = int((sub_paths["gene_set_library"] == "Reactome_2022").sum())
                hallmark_paths = int((sub_paths["gene_set_library"] == "MSigDB_Hallmark_2020").sum())
                gobp_paths = int((sub_paths["gene_set_library"] == "GO_Biological_Process_2021").sum())
            else:
                total_sig_paths = kegg_paths = reactome_paths = hallmark_paths = gobp_paths = 0

            # Descriptive theme
            if c == 0:
                theme = "ALL-predominant subgroup associated with elevated ribosomal, proteasomal, and metabolic gene expression"
            elif c == 1:
                theme = "Heterogeneous subgroup with mixed ALL/AML composition and broad transcriptional variation"
            elif c == 2:
                theme = "Subgroup enriched for AML samples with differential expression of myeloid-associated candidate markers"
            else:
                theme = "Unassigned Subgroup"

            rows.append({
                "cluster": c,
                "sample_count": n_samples,
                "cluster_proportion": round(prop, 4),
                "known_ALL_count": all_count,
                "known_AML_count": aml_count,
                "ALL_percentage": round(all_pct, 2),
                "AML_percentage": round(aml_pct, 2),
                "mean_PC1": round(mean_pc1, 4),
                "mean_PC2": round(mean_pc2, 4),
                "mean_PC3": round(mean_pc3, 4),
                "std_PC1": round(std_pc1, 4),
                "std_PC2": round(std_pc2, 4),
                "std_PC3": round(std_pc3, 4),
                "total_tested_probes": tested_probes,
                "fdr_significant_biomarkers": fdr_sig,
                "strong_candidate_count": strong_count,
                "strong_candidates_higher": strong_higher,
                "strong_candidates_lower": strong_lower,
                "significant_pathways_total": total_sig_paths,
                "significant_pathways_kegg": kegg_paths,
                "significant_pathways_reactome": reactome_paths,
                "significant_pathways_hallmark": hallmark_paths,
                "significant_pathways_gobp": gobp_paths,
                "primary_biological_theme": theme,
            })

        return pd.DataFrame(rows)

    def build_biomarker_integration(self) -> pd.DataFrame:
        """
        Integrates candidate biomarker probes with cluster metadata, annotations,
        and statistical measures.
        """
        df = self.strong_candidates_df.copy()

        # Determine annotation status
        def get_annotation_status(row: pd.Series) -> str:
            sym = row.get("gene_symbol")
            if pd.isna(sym) or not str(sym).strip() or str(sym).strip() in {"---", "nan", "None"}:
                return "unmapped"
            if "///" in str(sym):
                return "ambiguous"
            return "unambiguous"

        df["annotation_status"] = df.apply(get_annotation_status, axis=1)

        cols_to_include = [
            "cluster",
            "gene",
            "gene_symbol",
            "gene_title",
            "entrez_gene_id",
            "direction",
            "rank_biserial",
            "median_difference",
            "mann_whitney_u",
            "p_value",
            "fdr",
            "annotation_status",
        ]
        available_cols = [c for c in cols_to_include if c in df.columns]
        result = df[available_cols].sort_values(["cluster", "fdr", "rank_biserial"], ascending=[True, True, False])
        return result

    def build_pathway_integration(self) -> pd.DataFrame:
        """
        Summarizes Phase 7 significant pathway results per cluster.
        """
        if self.enrichment_sig_df.empty:
            return pd.DataFrame(columns=[
                "cluster",
                "gene_set_library",
                "pathway_name",
                "overlap_count",
                "pathway_size_in_background",
                "query_gene_count",
                "background_gene_count",
                "odds_ratio",
                "raw_p_value",
                "adjusted_p_value",
                "overlapping_genes",
            ])

        df = self.enrichment_sig_df.copy()
        renamed = df.rename(columns={
            "Term": "pathway_name",
            "P-value": "raw_p_value",
            "FDR_BH": "adjusted_p_value",
            "Odds Ratio": "odds_ratio",
            "Genes": "overlapping_genes",
        })

        cols_to_keep = [
            "cluster",
            "gene_set_library",
            "pathway_name",
            "overlap_count",
            "pathway_size_in_background",
            "query_gene_count",
            "background_gene_count",
            "odds_ratio",
            "raw_p_value",
            "adjusted_p_value",
            "overlapping_genes",
        ]
        available = [c for c in cols_to_keep if c in renamed.columns]
        result = renamed[available].sort_values(["cluster", "gene_set_library", "adjusted_p_value"])
        return result

    def build_cross_cluster_comparison(self) -> pd.DataFrame:
        """
        Computes formal cross-cluster statistical comparisons:
        - 2x2 Fisher's exact tests for known ALL/AML label distribution
        - Pairwise Jaccard similarity of FDR-significant biomarker probes
        - Centroid distance in 3D PCA space
        """
        merged_samples = self.clusters_df.merge(self.labels_df, on="sample_id")
        merged_pca = merged_samples.merge(self.pca_df[["sample_id", "PC1", "PC2", "PC3"]], on="sample_id")

        clusters = sorted(self.clusters_df["cluster"].unique())
        comparisons = []

        for i in range(len(clusters)):
            for j in range(i + 1, len(clusters)):
                ca = clusters[i]
                cb = clusters[j]

                # Phenotype distribution
                sa = merged_samples[merged_samples["cluster"] == ca]
                sb = merged_samples[merged_samples["cluster"] == cb]
                all_a = int((sa["cancer_type"] == "ALL").sum())
                aml_a = int((sa["cancer_type"] == "AML").sum())
                all_b = int((sb["cancer_type"] == "ALL").sum())
                aml_b = int((sb["cancer_type"] == "AML").sum())

                # Fisher exact test (testing odds of ALL vs AML between cluster A and cluster B)
                # Contingency table: [[ALL_A, ALL_B], [AML_A, AML_B]]
                table_2x2 = [[all_a, all_b], [aml_a, aml_b]]
                odds_ratio, p_val = fisher_exact(table_2x2)

                # Biomarker comparison
                sig_probes_a = set(
                    self.all_biomarkers_df[
                        (self.all_biomarkers_df["cluster"] == ca) & (self.all_biomarkers_df["fdr"] <= 0.05)
                    ]["gene"]
                )
                sig_probes_b = set(
                    self.all_biomarkers_df[
                        (self.all_biomarkers_df["cluster"] == cb) & (self.all_biomarkers_df["fdr"] <= 0.05)
                    ]["gene"]
                )

                shared_sig = len(sig_probes_a.intersection(sig_probes_b))
                union_sig = len(sig_probes_a.union(sig_probes_b))
                jaccard_sig = shared_sig / union_sig if union_sig > 0 else 0.0

                strong_a = set(self.strong_candidates_df[self.strong_candidates_df["cluster"] == ca]["gene"])
                strong_b = set(self.strong_candidates_df[self.strong_candidates_df["cluster"] == cb]["gene"])
                shared_strong = len(strong_a.intersection(strong_b))

                # PCA centroid distance
                pca_a = merged_pca[merged_pca["cluster"] == ca][["PC1", "PC2", "PC3"]].mean().to_numpy()
                pca_b = merged_pca[merged_pca["cluster"] == cb][["PC1", "PC2", "PC3"]].mean().to_numpy()
                centroid_dist = float(np.linalg.norm(pca_a - pca_b))

                comparisons.append({
                    "comparison": f"Cluster {ca} vs Cluster {cb}",
                    "cluster_a": ca,
                    "cluster_b": cb,
                    "samples_a": len(sa),
                    "samples_b": len(sb),
                    "phenotype_contingency": f"ALL: {all_a} vs {all_b} | AML: {aml_a} vs {aml_b}",
                    "fisher_odds_ratio": round(odds_ratio, 4) if not np.isinf(odds_ratio) else np.inf,
                    "fisher_exact_p_value": float(p_val),
                    "shared_significant_probes": shared_sig,
                    "union_significant_probes": union_sig,
                    "biomarker_jaccard_similarity": round(jaccard_sig, 4),
                    "shared_strong_candidate_probes": shared_strong,
                    "pca_centroid_euclidean_distance": round(centroid_dist, 4),
                })

        return pd.DataFrame(comparisons)

