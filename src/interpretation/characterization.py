def calculate_sha256(filepath: Path) -> str:
    """Compute SHA-256 checksum of a file."""
    if not filepath.is_file():
        return ""
    hasher = hashlib.sha256()
    with filepath.open("rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            hasher.update(chunk)
    return hasher.hexdigest()

def select_top_biomarkers(
    strong: pd.DataFrame,
    top_n: int = 6,
) -> pd.DataFrame:
    """Select the top N biomarkers per cluster by absolute effect size."""
    if top_n < 1:
        raise ValueError("top_n must be at least 1")

    if strong.empty:
        return strong.copy()

    required = {"cluster", "rank_biserial"}
    missing = required - set(strong.columns)
    if missing:
        raise ValueError(f"Missing required columns: {sorted(missing)}")

    selected = []
    for _, group in strong.groupby("cluster", sort=True):
        ranked = group.assign(
            _abs_effect=group["rank_biserial"].abs()
        ).sort_values("_abs_effect", ascending=False, kind="stable")
        selected.append(ranked.head(top_n).drop(columns="_abs_effect"))

    return pd.concat(selected).reset_index(drop=True)


